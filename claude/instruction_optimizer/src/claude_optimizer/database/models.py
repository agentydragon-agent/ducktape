class DatabaseManager:
    """Manages database connections and operations."""
    
    def __init__(self, database_url: str = "sqlite:///optimizer.db"):
        self.database_url = database_url
        self.engine = create_engine(database_url, echo=False)
        self.SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=self.engine)
        
    def create_tables(self):
        """Create all database tables."""
        Base.metadata.create_all(bind=self.engine)
        
    def get_session(self) -> Session:
        """Get a new database session."""
        return self.SessionLocal()
    
    def close(self):
        """Close the database connection."""
        self.engine.dispose()


# Global database manager instance
db_manager: Optional[DatabaseManager] = None


def init_database(database_url: str = "sqlite:///optimizer.db") -> DatabaseManager:
    """Initialize the global database manager."""
    global db_manager
    db_manager = DatabaseManager(database_url)
    db_manager.create_tables()
    return db_manager


def get_db_session() -> Session:
    """Get a database session from the global manager."""
    if db_manager is None:
        raise RuntimeError("Database not initialized. Call init_database() first.")
    return db_manager.get_session()


# Auto-update timestamps on updates
@event.listens_for(SeedTask, 'before_update')
def update_seed_task_timestamp(mapper, connection, target):
    target.updated_at = datetime.utcnow()


@event.listens_for(GradingCriteria, 'before_update')  
def update_grading_criteria_timestamp(mapper, connection, target):
    target.updated_at = datetime.utcnow()
