class RolloutFile(Base):
    """
    Agent output files, stored as path + SHA256 hash only.
    
    This table stores metadata about files created by agents, but NOT the file
    content itself. Content stays on the filesystem and is verified using SHA256
    hashes. This provides efficient storage while maintaining data integrity.
    """
    __tablename__ = 'rollout_files'
    __table_args__: ClassVar[dict] = {'comment': 'Metadata for agent-created files (content stored on filesystem, verified by SHA256)'}
    
    id = Column(Integer, primary_key=True, comment='Unique identifier for each file record')
    rollout_id = Column(Integer, ForeignKey('rollouts.id'), nullable=False,
                       comment='Which rollout created this file')
    relative_path = Column(Text, nullable=False, 
                          comment='Path relative to rollout directory (e.g., "main.py")')
    absolute_path = Column(Text, nullable=False, 
                          comment='Full filesystem path where the actual file content is stored')
    content_sha256 = Column(Text, nullable=False, 
                           comment='SHA256 hash of file content for integrity verification')
    file_size = Column(Integer, nullable=False, comment='File size in bytes')
    is_truncated = Column(Boolean, default=False, 
                         comment='Whether file content was truncated for API limits')
    is_binary = Column(Boolean, default=False, comment='Whether this is a binary file')
    created_at = Column(DateTime, default=datetime.utcnow, comment='When this file record was created')
    
    # Relationships
    rollout = relationship("Rollout", back_populates="files")
    
    def verify_file_integrity(self) -> bool:
        """Verify that the file on disk matches the stored SHA256 hash."""
        file_path = Path(self.absolute_path)
        if not file_path.exists():
            return False
        
        try:
            with file_path.open('rb') as f:
                content = f.read()
            
            actual_hash = hashlib.sha256(content).hexdigest()
            return actual_hash == self.content_sha256
        except OSError as e:
            # File system errors (permissions, disk full, etc.) should not be hidden
            # These are unrecoverable and indicate serious problems
            raise RuntimeError(f"Failed to verify file integrity for {self.absolute_path}: {e}") from e
    
    def read_content(self) -> str:
        """Read and return file content, verifying integrity."""
        if not self.verify_file_integrity():
            raise ValueError(f"File integrity check failed for {self.absolute_path}")
        
        with self.absolute_path.open(encoding='utf-8') as f:
            return f.read()
    
    @classmethod
    def compute_file_hash(cls, file_path: Path) -> str:
        """Compute SHA256 hash of file content."""
        with file_path.open('rb') as f:
            content = f.read()
        return hashlib.sha256(content).hexdigest()


