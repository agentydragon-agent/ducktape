test("emitBrowserHarness materializes pipeline artifacts into a local runnable app shell", async () => {
  const { appRoot, extractedRoot, snapshotRoot } = createWebFixtureRoots("debundle-browser-harness-test-");

  writeHarnessFixture({
    cssEntries: ["preload/style.css"],
    extractedRoot,
    files: {
      "preload/style.css": `.app { color: red; }\n`,
      "static/app.js": `globalThis.events = globalThis.events ?? [];import { value } from "./vendor.js";globalThis.events.push("app:"+value);await import("./lazy.js").then(({lazy})=>globalThis.events.push("lazy:"+lazy));console.log(globalThis.events.join(","));export{value};\n`,
      "static/lazy.js": `globalThis.events.push("lazy-side-effect");const lazy=5;export{lazy};\n`,
      "static/vendor.js": `globalThis.events = globalThis.events ?? [];globalThis.events.push("vendor");const value=2;export{value};\n`,
    },
    html: `<!doctype html>
<html>
  <head>
    <link href="/preload/style.css" rel="stylesheet" />
    <link rel="modulepreload" crossorigin href="/static/vendor.js">
    <script type="module" crossorigin src="/static/app.js"></script>
  </head>
  <body>
    <div id="app"></div>
  </body>
</html>
`,
    jsEntries: ["static/app.js", "static/vendor.js"],
    snapshotRoot,
  });

  const splitResult = await buildNormalizedPipelineArtifactFromSnapshot({
    jsListPath: join(extractedRoot, "js-files.txt"),
    snapshotRoot,
  });

  const { manifest } = emitBrowserHarness({
    artifact: rewriteChunkEntrySpecifiers({ artifact: splitResult.artifact }).artifact,
    assetSummaryPath: join(extractedRoot, "asset-summary.json"),
    force: true,
    outDir: appRoot,
    scriptSource: "split",
    snapshotRoot,
  });

  assert.equal(manifest.scriptSource, "split");
  assert.equal(manifest.chunksManifestPath, join(appRoot, "chunks.manifest.json"));
  assert.deepEqual(manifest.entryScripts, ["static/app.js"]);
  assert.deepEqual(manifest.modulePreloads, ["static/vendor.js"]);
  assert.ok(existsSync(join(appRoot, "preload", "style.css")));
  assert.equal(existsSync(join(appRoot, "static", "app.js")), false);
  assert.ok(existsSync(join(appRoot, "static", "app", SPLIT_ENTRY_FILE)));
  assert.ok(existsSync(join(appRoot, "static", "app", "manifest.json")));
  assert.ok(existsSync(join(appRoot, "static", "vendor", SPLIT_ENTRY_FILE)));
  assert.ok(existsSync(join(appRoot, "static", "vendor", "manifest.json")));

  const indexHtml = readUtf8(join(appRoot, "index.html"));
  assert.match(indexHtml, /Generated local harness/);
  assert.match(indexHtml, /__debundleHarness/);
  assert.match(indexHtml, /href="\.\/preload\/style\.css"/);
  assert.match(indexHtml, /href="\.\/static\/vendor\/entry\.js"/);
  assert.match(indexHtml, /src="\.\/bootstrap\.js"/);

  const bootstrap = readUtf8(join(appRoot, "bootstrap.js"));
  assert.equal(
    bootstrap,
    `// Generated by //devinfra/js/debundle/transforms:run_transform.\n// Loads original HTML module script entries from split output.\n\nimport "./static/app/entry.js";\n`
  );

  assert.deepEqual(runNodeScript(join(appRoot, "bootstrap.js")), runNodeScript(join(snapshotRoot, "static", "app.js")));
});

test("emitBrowserHarness works without manifests and with no emitted parts", () => {
  const { appRoot, extractedRoot, snapshotRoot } = createWebFixtureRoots("debundle-browser-harness-no-manifest-");

  writeHarnessFixture({
    extractedRoot,
    files: {
      "static/app.js": `globalThis.events = ["app"]; console.log(globalThis.events.join(",")); export const value = 1;\n`,
    },
    html: `<!doctype html><html><head><script type="module" src="/static/app.js"></script></head><body></body></html>\n`,
    jsEntries: ["static/app.js"],
    snapshotRoot,
  });

  const artifact = createArtifact({
    chunks: [
      {
        chunkId: "static/app",
        entryFile: "entry.js",
        files: [
          createFile({
            path: "entry.js",
            ast: parseModuleCode(readUtf8(join(snapshotRoot, "static", "app.js"))),
            metadata: {
              chunkId: "static/app",
              chunkFile: "entry.js",
              role: "entry",
            },
          }),
        ],
      },
    ],
  });

  emitBrowserHarness({
    artifact,
    assetSummaryPath: join(extractedRoot, "asset-summary.json"),
    force: true,
    outDir: appRoot,
    scriptSource: "split",
    snapshotRoot,
  });

  assert.equal(existsSync(join(appRoot, "static", "app", "runtime.js")), false);
  assert.ok(existsSync(join(appRoot, "static", "app", "entry.js")));
  assert.equal(existsSync(join(appRoot, "static", "app", "parts")), false);
  assert.equal(existsSync(join(appRoot, "static", "app", "manifest.json")), false);
  assert.ok(existsSync(join(appRoot, "chunks.manifest.json")));
  assert.match(readUtf8(join(appRoot, "bootstrap.js")), /import "\.\/static\/app\/entry\.js";/);
  assert.deepEqual(runNodeScript(join(appRoot, "bootstrap.js")), runNodeScript(join(snapshotRoot, "static", "app.js")));
});

test("emitBrowserHarness rejects materialized artifact scripts that do not parse", () => {
  const { appRoot, extractedRoot, snapshotRoot } = createWebFixtureRoots("debundle-browser-harness-syntax-");

  writeHarnessFixture({
    extractedRoot,
    files: {
      "static/app.js": `console.log("source fixture");\n`,
    },
    html: `<!doctype html><html><head><script type="module" src="/static/app.js"></script></head><body></body></html>\n`,
    jsEntries: ["static/app.js"],
    snapshotRoot,
  });

  const artifact = createArtifact({
    chunks: [
      {
        chunkId: "static/app",
        entryFile: "entry.js",
        files: [
          createFile({
            path: "entry.js",
            ast: invalidReservedDefaultBindingAst(),
            metadata: {
              chunkId: "static/app",
              chunkFile: "entry.js",
              role: "entry",
            },
          }),
        ],
      },
    ],
  });

  assert.throws(
    () =>
      emitBrowserHarness({
        artifact,
        assetSummaryPath: join(extractedRoot, "asset-summary.json"),
        force: true,
        outDir: appRoot,
        scriptSource: "split",
        snapshotRoot,
      }),
    (error) => {
      assert.match(error.message, /emitBrowserHarness emitted invalid JavaScript/);
      assert.match(error.message, /static\/app\/entry\.js/);
      assert.match(error.message, /default/);
      return true;
    }
  );
});

