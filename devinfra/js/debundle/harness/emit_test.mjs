test("emitBrowserHarness preserves sibling analysis and vendor outputs under the app root", () => {
  const { appRoot, extractedRoot, snapshotRoot } = createWebFixtureRoots("debundle-browser-harness-preserve-siblings-");

  writeHarnessFixture({
    extractedRoot,
    files: {
      "static/app.js": `export const value = 1;\n`,
    },
    html: `<!doctype html><html><head><script type="module" src="/static/app.js"></script></head><body></body></html>\n`,
    jsEntries: ["static/app.js"],
    snapshotRoot,
  });

  const artifact = createArtifact({
    chunks: [
      {
        chunkId: "static/app",
        entryFile: "entry.js",
        files: [
          createFile({
            path: "entry.js",
            ast: parseModuleCode(readUtf8(join(snapshotRoot, "static", "app.js"))),
            metadata: {
              chunkId: "static/app",
              chunkFile: "entry.js",
              role: "entry",
            },
          }),
        ],
      },
    ],
  });

  const analysisPath = join(appRoot, "analysis", "scrambled-identifiers.json");
  const vendorManifestPath = join(appRoot, "vendors", "manifest.json");
  const wrapperPath = join(appRoot, "vendors", "generated", "static", "fixture", "entry.js");
  writeJsonFile(analysisPath, { kind: "analysis.fixture" });
  writeJsonFile(vendorManifestPath, { kind: "js.vendor_resolution_manifest", resolutions: {} });
  writeTextFile(wrapperPath, "export const wrapper = true;\n");

  emitBrowserHarness({
    artifact,
    assetSummaryPath: join(extractedRoot, "asset-summary.json"),
    force: true,
    outDir: appRoot,
    scriptSource: "split",
    snapshotRoot,
    vendorManifestPath,
  });

  assert.equal(readUtf8(analysisPath), '{\n  "kind": "analysis.fixture"\n}\n');
  assert.equal(readUtf8(vendorManifestPath), '{\n  "kind": "js.vendor_resolution_manifest",\n  "resolutions": {}\n}\n');
  assert.equal(readUtf8(wrapperPath), "export const wrapper = true;\n");
  assert.ok(existsSync(join(appRoot, "static", "app", "entry.js")));
});

function invalidReservedDefaultBindingAst() {
  return t.file(
    t.program([
      t.variableDeclaration("const", [t.variableDeclarator(t.identifier("source"), t.objectExpression([]))]),
      t.variableDeclaration("const", [
        t.variableDeclarator(
          t.objectPattern([t.objectProperty(t.identifier("default"), t.identifier("default"), false, true)]),
          t.identifier("source")
        ),
      ]),
    ])
  );
}

test("emitBrowserHarness records vendor resolutions and omits swapped chunks from the app tree", async () => {
  const { appRoot, extractedRoot, packagesRoot, root, snapshotRoot, vendorsRoot } = createWebFixtureRoots(
    "debundle-browser-harness-vendor-"
  );
  const vendorManifestPath = join(vendorsRoot, "manifest.json");

  writeHarnessFixture({
    extractedRoot,
    files: {
      "static/app.js": `import { render } from "./katex.js";globalThis.__render=render;export{render};\n`,
      "static/katex.js": `const render=()=>"rendered";export{render};\n`,
    },
    html: `<!doctype html><html><head><script type="module" crossorigin src="/static/app.js"></script></head><body></body></html>\n`,
    jsEntries: ["static/app.js"],
    snapshotRoot,
  });

  const upstreamKatex = 'export const render = () => "upstream";\nexport const version = "0.16.11";\n';
  writeTextFile(join(packagesRoot, "katex", "dist", "katex.mjs"), upstreamKatex);
  writeJsonFile(join(packagesRoot, "katex", "package.json"), {
    name: "katex",
    version: "0.16.11",
  });
  writeJsonFile(vendorManifestPath, {
    kind: "js.vendor_resolution_manifest",
    uiVersion: FIXTURE_UI_VERSION,
    resolutions: {
      "static/katex.js": {
        entryFile: "entry.js",
        package: "katex",
        version: "0.16.11",
        subpath: "dist/katex.mjs",
      },
    },
  });

  const splitResult = await buildNormalizedPipelineArtifactFromSnapshot({
    jsListPath: join(extractedRoot, "js-files.txt"),
    snapshotRoot,
  });

  const { manifest: metadataHarnessManifest } = emitBrowserHarness({
    artifact: rewriteChunkEntrySpecifiers({ artifact: splitResult.artifact }).artifact,
    assetSummaryPath: join(extractedRoot, "asset-summary.json"),
    force: true,
    outDir: appRoot,
    scriptSource: "split",
    snapshotRoot,
    vendorManifestPath,
  });

  assert.equal(metadataHarnessManifest.vendorManifestPath, vendorManifestPath);
  assert.equal(metadataHarnessManifest.vendorResolutions.length, 1);
  assert.equal(metadataHarnessManifest.vendorResolutions[0].chunkId, "static/katex");
  assert.equal(metadataHarnessManifest.vendorResolutions[0].package, "katex");
  assert.equal(metadataHarnessManifest.vendorResolutions[0].version, "0.16.11");
  assert.equal(existsSync(join(appRoot, "static", "katex", SPLIT_ENTRY_FILE)), true);

  const swappedArtifact = swapVendorChunks({
    artifact: splitResult.artifact,
    packagesRoot,
    operations: [
      {
        id: "swap_fixture_katex",
        operation: "mark_vendor",
        level: "swap",
        chunkPath: "static/katex.js",
        identity: "katex/dist/katex.mjs",
        package: "katex",
        subpath: "dist/katex.mjs",
        version: "0.16.11",
        evidence: [{ path: "static/katex.js", text: "fixture" }],
      },
    ],
    outputManifestPath: vendorManifestPath,
    outputWrapperDir: join(vendorsRoot, "generated"),
    write: true,
  });

  const artifactVendorAppRoot = join(root, "app-artifact");
  const { manifest: artifactVendorHarnessManifest } = emitBrowserHarness({
    artifact: rewriteChunkEntrySpecifiers({ artifact: swappedArtifact.artifact }).artifact,
    assetSummaryPath: join(extractedRoot, "asset-summary.json"),
    force: true,
    outDir: artifactVendorAppRoot,
    scriptSource: "split",
    snapshotRoot,
    vendorManifestPath,
  });

  assert.equal(artifactVendorHarnessManifest.vendorResolutions.length, 1);
  assert.equal(existsSync(join(artifactVendorAppRoot, "static", "katex", SPLIT_ENTRY_FILE)), false);

  const generatedWrapperPath = join(vendorsRoot, "generated", "static", "cytoscape", "entry.js");
  writeTextFile(generatedWrapperPath, "export default __vendor_default__;\nexport const c = __vendor_default__;\n");
  writeJsonFile(vendorManifestPath, {
    kind: "js.vendor_resolution_manifest",
    uiVersion: FIXTURE_UI_VERSION,
    resolutions: {
      "static/cytoscape.js": {
        entryFile: "entry.js",
        package: "cytoscape",
        version: "3.30.4",
        subpath: "dist/cytoscape.esm.mjs",
        wrapperShape: "named-from-module-default",
        generatedWrapperPath: "vendors/generated/static/cytoscape/entry.js",
      },
    },
  });

  const { manifest: wrapperHarnessManifest } = emitBrowserHarness({
    artifact: rewriteChunkEntrySpecifiers({ artifact: swappedArtifact.artifact }).artifact,
    assetSummaryPath: join(extractedRoot, "asset-summary.json"),
    force: true,
    outDir: appRoot,
    scriptSource: "split",
    snapshotRoot,
    vendorManifestPath,
  });
  assert.equal(wrapperHarnessManifest.vendorResolutions.length, 1);
  assert.equal(wrapperHarnessManifest.vendorResolutions[0].chunkId, "static/cytoscape");
  assert.equal(wrapperHarnessManifest.vendorResolutions[0].generatedWrapperPath, generatedWrapperPath);
  assert.equal(existsSync(join(appRoot, "static", "cytoscape", SPLIT_ENTRY_FILE)), false);
});
